/**
 * Archive the daily diesel alerts published before #168 (see fuel-articles.ts).
 * /noticias/<slug> then 308s to /precio-diesel-hoy, and the sitemap and every
 * list drop them (they all read status PUBLISHED). Reversible: status only.
 *
 *   npx tsx scripts/archive-fuel-alerts.ts                     # dry run
 *   npx tsx scripts/archive-fuel-alerts.ts --apply --expect 123
 *
 * --apply runs one transaction and rolls back unless exactly --expect rows
 * changed.
 */

import pg from "pg";
import { FIXED_AT, SINCE } from "./fuel-articles.js";

const WHERE = `status = 'PUBLISHED' AND category = 'PRICE_ALERT' AND source = 'MITERD'
  AND "isAutoGenerated" = true AND slug LIKE 'precio-diesel-%'
  AND "publishedAt" >= $1 AND "publishedAt" < $2`;

async function main() {
  const args = process.argv.slice(2);
  const apply = args.includes("--apply");
  const expect = Number(args[args.indexOf("--expect") + 1]);
  if (apply && !(args.includes("--expect") && Number.isInteger(expect) && expect > 0)) {
    throw new Error("--apply needs --expect <count> from the dry run");
  }
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is not set");

  const pool = new pg.Pool({ connectionString: url, max: 1 });
  const client = await pool.connect();
  try {
    const found = await client.query(
      `SELECT id, slug, "publishedAt" FROM "Article" WHERE ${WHERE} ORDER BY "publishedAt"`,
      [SINCE, FIXED_AT]
    );
    const rows = found.rows as { id: string; slug: string; publishedAt: Date }[];
    console.log(`diesel alerts to archive: ${rows.length}`);
    if (rows.length) {
      console.log(`  first: ${rows[0].id} ${rows[0].slug}`);
      console.log(`  last:  ${rows[rows.length - 1].id} ${rows[rows.length - 1].slug}`);
    }
    if (!apply) {
      console.log("dry run: nothing written. Apply with --apply --expect " + rows.length);
      return;
    }

    await client.query("BEGIN");
    const done = await client.query(`UPDATE "Article" SET status = 'ARCHIVED' WHERE ${WHERE} RETURNING id`, [
      SINCE,
      FIXED_AT,
    ]);
    if (done.rowCount !== expect) {
      await client.query("ROLLBACK");
      throw new Error(`would archive ${done.rowCount}, expected ${expect}: rolled back`);
    }
    await client.query("COMMIT");
    console.log(`archived ${done.rowCount} (committed)`);
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
