/**
 * Remove the false fuel deltas from the daily, fuel and weekly reports
 * published before #168, with a dated note (see fuel-articles.ts). URL,
 * publishedAt and updatedAt stay as they are.
 *
 *   npx tsx scripts/correct-fuel-reports.ts                     # dry run
 *   npx tsx scripts/correct-fuel-reports.ts --apply --expect 290
 *
 * The dry run prints, per family, how many reports change and one sample
 * diff. --apply refuses while any report keeps delta text after correcting (a
 * variant to handle first), runs one transaction, updates each row only if
 * its body is still the one read, and rolls back unless exactly --expect rows
 * changed.
 */

import pg from "pg";
import { FAMILY_PREFIX, FIXED_AT, SINCE, correct, familyOf, type Family } from "./fuel-articles.js";

interface Row {
  id: string;
  slug: string;
  body: string;
  summary: string;
}

function sampleDiff(before: string, after: string): string {
  const a = before.split("\n");
  const b = new Set(after.split("\n"));
  const gone = a.filter((l) => !b.has(l));
  const added = after.split("\n").filter((l) => !a.includes(l));
  return [...gone.map((l) => `  - ${l}`), ...added.map((l) => `  + ${l}`)].join("\n");
}

async function main() {
  const args = process.argv.slice(2);
  const apply = args.includes("--apply");
  const expect = Number(args[args.indexOf("--expect") + 1]);
  if (apply && !(args.includes("--expect") && Number.isInteger(expect) && expect > 0)) {
    throw new Error("--apply needs --expect <count> from the dry run");
  }
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is not set");

  const pool = new pg.Pool({ connectionString: url, max: 1 });
  const client = await pool.connect();
  try {
    const prefixes = Object.values(FAMILY_PREFIX).map((p) => `${p}%`);
    const found = await client.query(
      `SELECT id, slug, body, summary FROM "Article"
       WHERE status = 'PUBLISHED' AND "isAutoGenerated" = true AND slug LIKE ANY($1)
         AND "publishedAt" >= $2 AND "publishedAt" < $3
       ORDER BY "publishedAt"`,
      [prefixes, SINCE, FIXED_AT]
    );
    const rows = found.rows as Row[];

    const changes: { row: Row; body: string; summary: string }[] = [];
    const stats: Record<Family, { read: number; change: number; leftover: string[] }> = {
      daily: { read: 0, change: 0, leftover: [] },
      fuel: { read: 0, change: 0, leftover: [] },
      weekly: { read: 0, change: 0, leftover: [] },
    };
    const samples = new Map<Family, string>();
    for (const row of rows) {
      const family = familyOf(row.slug);
      if (!family) continue;
      stats[family].read++;
      const c = correct(family, row.body, row.summary);
      if (!c) continue;
      stats[family].change++;
      if (c.leftover) stats[family].leftover.push(row.slug);
      changes.push({ row, body: c.body, summary: c.summary });
      if (!samples.has(family)) {
        samples.set(
          family,
          `${row.slug}\n${sampleDiff(row.body, c.body)}` +
            (c.summary !== row.summary ? `\n  summary - ${row.summary}\n  summary + ${c.summary}` : "")
        );
      }
    }

    for (const [family, s] of Object.entries(stats)) {
      console.log(`${family}: ${s.read} read, ${s.change} to correct, ${s.leftover.length} with delta text left`);
      for (const slug of s.leftover.slice(0, 5)) console.log(`  left: ${slug}`);
    }
    for (const [family, diff] of samples) console.log(`\nsample (${family}): ${diff}`);
    const leftovers = Object.values(stats).reduce((n, s) => n + s.leftover.length, 0);
    console.log(`\ntotal to correct: ${changes.length}`);

    if (!apply) {
      console.log(`dry run: nothing written. Apply with --apply --expect ${changes.length}`);
      return;
    }
    if (leftovers > 0) throw new Error(`${leftovers} reports keep delta text: handle that variant first`);

    await client.query("BEGIN");
    let updated = 0;
    for (const c of changes) {
      const r = await client.query(
        `UPDATE "Article" SET body = $1, summary = $2 WHERE id = $3 AND body = $4 AND status = 'PUBLISHED'`,
        [c.body, c.summary, c.row.id, c.row.body]
      );
      updated += r.rowCount ?? 0;
    }
    if (updated !== expect) {
      await client.query("ROLLBACK");
      throw new Error(`would correct ${updated}, expected ${expect}: rolled back`);
    }
    await client.query("COMMIT");
    console.log(`corrected ${updated} (committed)`);
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
